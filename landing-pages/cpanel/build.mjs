#!/usr/bin/env node
/**
 * Build the cPanel version of the landing pages for https://workspacejunction.com/thanks-giving/
 *   node cpanel/build.mjs            -> dist/thanks-giving/ (+ dist/thanks-giving-config.php with live keys, never zipped)
 * Clean URLs (/thanks-giving/podcast-studio), PHP API, private folder blocked by .htaccess.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const out = path.join(root, 'dist', 'thanks-giving');
const BASE = 'https://workspacejunction.com/thanks-giving/';
const PAGES = ['index', 'podcast-studio', 'conference-room', 'boardroom', 'dedicated-desk', 'mailbox', 'checkout-complete', '404'];

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
const copyDir = (src, dst) => fs.cpSync(src, dst, { recursive: true });

copyDir(path.join(root, 'assets'), path.join(out, 'assets'));
copyDir(path.join(here, 'api'), path.join(out, 'api'));
fs.mkdirSync(path.join(out, 'private'), { recursive: true });
fs.copyFileSync(path.join(here, 'private', 'lib.php'), path.join(out, 'private', 'lib.php'));
fs.copyFileSync(path.join(here, 'private', '.htaccess'), path.join(out, 'private', '.htaccess'));
fs.copyFileSync(path.join(here, '.htaccess'), path.join(out, '.htaccess'));

/* detect the current SEO base from sitemap.xml */
const sitemap = fs.readFileSync(path.join(root, 'sitemap.xml'), 'utf8');
const current = sitemap.match(/<loc>(https:\/\/[^<]+?\/)<\/loc>/)[1];

const pageRe = PAGES.join('|');
function transform(s) {
  s = s.split(current).join(BASE);
  // absolute page URLs -> clean
  s = s.replace(new RegExp(`(${BASE.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')})(${pageRe})\\.html`, 'g'), (m, b, p) => (p === 'index' ? b : b + p));
  // relative links: href="podcast-studio.html" -> href="podcast-studio", index.html -> ./
  s = s.replace(new RegExp(`href="(${pageRe})\\.html(#[^"]*)?"`, 'g'), (m, p, h) => `href="${p === 'index' ? './' : p}${h || ''}"`);
  return s;
}
for (const p of PAGES) {
  const src = path.join(root, p + '.html');
  if (fs.existsSync(src)) fs.writeFileSync(path.join(out, p + '.html'), transform(fs.readFileSync(src, 'utf8')));
}
fs.writeFileSync(path.join(out, 'sitemap.xml'), transform(sitemap));
/* IndexNow key file (Bing / Yandex / Seznam instant indexing) */
for (const f of fs.readdirSync(root)) if (/^[a-f0-9]{32}\.txt$/.test(f)) fs.copyFileSync(path.join(root, f), path.join(out, f));
fs.writeFileSync(path.join(out, 'robots.txt'), `User-agent: *\nAllow: /thanks-giving/\n\nSitemap: ${BASE}sitemap.xml\n`);

/* checkout-complete.js linked back to "index.html" pages via API `page` values (already clean in PHP). */
const cc = path.join(out, 'assets', 'js', 'checkout-complete.js');
fs.writeFileSync(cc, fs.readFileSync(cc, 'utf8'));

/* live config (kept OUT of the zip; uploaded separately to private/config.php) */
const envFile = path.join(root, 'server', '.env.production');
const env = Object.fromEntries(fs.readFileSync(envFile, 'utf8').split(/\r?\n/).filter(l => /^[A-Z_]+=/.test(l)).map(l => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1).trim()]));
const whsecFile = path.join(root, 'dist', 'thanks-giving-webhook-secret.txt');
const whsec = fs.existsSync(whsecFile) ? fs.readFileSync(whsecFile, 'utf8').trim() : '';
const readOpt = (f) => { const p = path.join(root, 'dist', f); return fs.existsSync(p) ? fs.readFileSync(p, 'utf8').trim() : ''; };
const relayUrl = readOpt('mail-relay-url.txt');
const relaySecret = readOpt('mail-relay-secret.txt');
const php = (v) => `'${String(v).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const config = `<?php
// LIVE configuration for /thanks-giving/ (generated by cpanel/build.mjs). Blocked from the web by private/.htaccess.
return [
  'public_url' => ${php(BASE.replace(/\/$/, ''))},
  'allowed_origins' => ['https://workspacejunction.com', 'https://www.workspacejunction.com'],
  'stripe' => [
    'secret_key' => ${php(env.STRIPE_SECRET_KEY)},
    'publishable_key' => ${php(env.STRIPE_PUBLISHABLE_KEY)},
    'webhook_secret' => ${php(whsec)},
  ],
  'promo' => [
    'desk' => ['limit' => ${Number(env.DESK_PROMO_LIMIT || 10)}, 'claimed_base' => ${Number(env.DESK_CLAIMED_BASE || 0)}],
    'mailbox' => ['limit' => ${Number(env.MAILBOX_PROMO_LIMIT || 50)}, 'claimed_base' => ${Number(env.MAILBOX_CLAIMED_BASE || 0)}],
  ],
  'mail' => [
    'from' => 'Workspace Junction <noreply@workspacejunction.com>',
    'reply_to' => 'grow@workspacejunction.com',
    'notify' => [${(env.NOTIFY_EMAIL || 'nabeel@digaptics.com').split(',').map(s => php(s.trim())).join(', ')}],
    'redirect_to' => [],
    // Customers receive NO emails from the site; the team follows up manually.
    'customer_emails' => ${String(env.CUSTOMER_EMAILS || 'false').toLowerCase() === 'true' ? 'true' : 'false'},
    // HTTPS mail relay (Google Apps Script "WJ Thanksgiving Mail Relay" under moid.officework@gmail.com)
    'relay_url' => ${php(relayUrl)},
    'relay_secret' => ${php(relaySecret)},
  ],
];
`;
fs.writeFileSync(path.join(root, 'dist', 'thanks-giving-config.php'), config, { mode: 0o600 });

const count = (d) => fs.readdirSync(d, { withFileTypes: true }).reduce((n, e) => n + (e.isDirectory() ? count(path.join(d, e.name)) : 1), 0);
console.log(`built ${out} (${count(out)} files), webhook secret ${whsec ? 'included' : 'NOT set yet'}`);
